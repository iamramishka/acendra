// Manual browser verification of the production reader using synthetic content.
// flutter build web --target test/browser/protected_pdf_preview.dart --release
//   --no-pub --output build/pdf-preview
// Then copy test/fixtures/csa271_watermarked.pdf into build/pdf-preview/fixtures/
// and serve build/pdf-preview on loopback. This does not test hosted delivery.
import 'dart:js_interop';
import 'package:acendra/app/theme/app_theme.dart';
import 'package:acendra/features/pdf_reader/data/pdf_outline_web.dart';
import 'package:acendra/features/pdf_reader/data/pdf_reading_store.dart';
import 'package:acendra/features/pdf_reader/domain/entities/pdf_outline_entry.dart';
import 'package:acendra/features/pdf_reader/presentation/widgets/pdf_lesson_reader.dart';
import 'package:flutter/material.dart';
import 'package:pdfx/pdfx.dart' as pdfx;
import 'package:web/web.dart' as web;

Future<void> main() async {
  final binding = WidgetsFlutterBinding.ensureInitialized();
  // Keep the semantics handle alive for browser keyboard and AX verification.
  binding.ensureSemantics();
  try {
    final response = await web.window
        .fetch('/fixtures/csa271_watermarked.pdf'.toJS)
        .toDart;
    if (response.status != 200) {
      throw StateError('Synthetic fixture unavailable');
    }
    final bytes = (await response.arrayBuffer().toDart).toDart.asUint8List();
    final outline = await loadPdfOutline(bytes);
    final document = await pdfx.PdfDocument.openData(bytes);
    runApp(_Preview(document: document, outline: outline));
  } catch (error) {
    runApp(MaterialApp(home: Scaffold(body: Text('Preview failed: $error'))));
  }
}

class _Preview extends StatefulWidget {
  const _Preview({required this.document, required this.outline});
  final pdfx.PdfDocument document;
  final List<PdfOutlineEntry> outline;
  @override
  State<_Preview> createState() => _PreviewState();
}

class _PreviewState extends State<_Preview> {
  var _dark = false;
  var _reader = 0;
  var _otherStudent = false;
  @override
  Widget build(BuildContext context) => MaterialApp(
    theme: AppTheme.light,
    darkTheme: AppTheme.dark,
    themeMode: _dark ? ThemeMode.dark : ThemeMode.light,
    home: Scaffold(
      appBar: AppBar(
        title: Text(
          _otherStudent ? 'Synthetic student B' : 'Synthetic student A',
        ),
        actions: [
          IconButton(
            tooltip: 'Reopen guide',
            onPressed: () => setState(() => _reader++),
            icon: const Icon(Icons.refresh),
          ),
          IconButton(
            tooltip: 'Switch synthetic student',
            onPressed: () => setState(() {
              _otherStudent = !_otherStudent;
              _reader++;
            }),
            icon: const Icon(Icons.person_outline),
          ),
          IconButton(
            tooltip: 'Toggle theme',
            onPressed: () => setState(() => _dark = !_dark),
            icon: const Icon(Icons.brightness_6),
          ),
        ],
      ),
      body: PdfLessonReader(
        key: ValueKey(_reader),
        document: widget.document,
        store: PdfReadingStore(
          userId: _otherStudent ? 'preview-student-b' : 'preview-student-a',
          lessonId: 'csa271-synthetic',
        ),
        outline: widget.outline,
        // Fixture generated by tool/pdf_watermark using the actual v2 policy.
        // This preview has no authenticated descriptor or hosted connection.
        watermarkApplied: true,
        title: 'Responsive Layouts Guide',
      ),
    ),
  );
}
