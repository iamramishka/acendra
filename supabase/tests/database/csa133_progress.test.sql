begin;
select '1..1';
do $$
declare u uuid:=gen_random_uuid(); other_user uuid:=gen_random_uuid(); a uuid:=gen_random_uuid();
 us uuid:=gen_random_uuid(); os uuid:=gen_random_uuid(); ads uuid:=gen_random_uuid();
 c uuid:=gen_random_uuid(); s uuid:=gen_random_uuid(); l uuid:=gen_random_uuid();
 pdf uuid:=gen_random_uuid(); video uuid:=gen_random_uuid(); r jsonb; gid uuid;
begin
 insert into auth.users(id) values(u),(other_user),(a);
 insert into auth.sessions(id,user_id,aal,not_after) values(us,u,'aal1',now()+interval '1 day'),(os,other_user,'aal1',now()+interval '1 day'),(ads,a,'aal2',now()+interval '1 day');
 insert into public.user_roles(user_id,role_id) select a,id from public.roles where code='super_admin';
 insert into public.courses(id,slug,title,price_minor,status) values(c,'progress-'||c,'Synthetic progress',10000,'draft');
 insert into public.course_sections(id,course_id,title,position,is_published) values(s,c,'Section',0,true);
 insert into public.lessons(id,section_id,title,lesson_type,position,is_published,duration_seconds) values(l,s,'Text','text',0,true,null),(pdf,s,'PDF','pdf',1,true,null),(video,s,'Video','video',2,true,60);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',u,'session_id',us,'aal','aal1','role','authenticated')::text,true);
 begin perform public.csa133_save_progress(l,true,null,null,null); raise exception 'unpaid save'; exception when insufficient_privilege then null; end;
 gid:=(public.csa116_grant_admin(a,ads,'aal2','progress-grant',u,c,'Synthetic',null)->>'grant_id')::uuid;
 execute 'set local role authenticated';
 r:=public.csa133_save_progress(l,true,null,null,null);
 if jsonb_array_length(public.csa133_read_progress(c))<>1 then raise exception 'authenticated roundtrip'; end if;
 execute 'reset role';
 if r->>'lesson_id' is distinct from l::text or (r->>'is_completed')::boolean is not true then raise exception 'roundtrip'; end if;
 perform public.csa133_save_progress(l,false,null,null,null);
 if (select count(*) from public.lesson_progress where user_id=u and lesson_id=l)<>1 then raise exception 'duplicate progress'; end if;
 perform public.csa133_save_progress(pdf,false,3,0.5,null);
 perform public.csa133_save_progress(video,false,null,null,60);
 if jsonb_array_length(public.csa133_read_progress(c))<>3 then raise exception 'resume list'; end if;
 begin perform public.csa133_save_progress(l,true,1,0,null); raise exception 'text PDF position'; exception when invalid_parameter_value then null; end;
 begin perform public.csa133_save_progress(pdf,true,null,0.5,null); raise exception 'offset without page'; exception when invalid_parameter_value then null; end;
 begin perform public.csa133_save_progress(pdf,true,1,'NaN'::numeric,null); raise exception 'NaN offset'; exception when invalid_parameter_value then null; end;
 begin perform public.csa133_save_progress(video,true,null,null,61); raise exception 'duration overflow'; exception when invalid_parameter_value then null; end;
 update public.lessons set is_published=false where id=l;
 begin perform public.csa133_save_progress(l,true,null,null,null); raise exception 'unpublished lesson'; exception when insufficient_privilege then null; end;
 if jsonb_array_length(public.csa133_read_progress(c))<>2 then raise exception 'unpublished read'; end if;
 update public.lessons set is_published=true where id=l;
 update public.course_sections set is_published=false where id=s;
 begin perform public.csa133_save_progress(l,true,null,null,null); raise exception 'unpublished section'; exception when insufficient_privilege then null; end;
 update public.course_sections set is_published=true where id=s;
 update public.courses set status='archived' where id=c;
 perform public.csa133_save_progress(l,true,null,null,null);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',other_user,'session_id',os,'aal','aal1','role','authenticated')::text,true);
 begin perform public.csa133_read_progress(c); raise exception 'foreign read'; exception when insufficient_privilege then null; end;
 begin perform public.csa133_save_progress(l,true,null,null,null); raise exception 'foreign save'; exception when insufficient_privilege then null; end;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',u,'session_id',os,'aal','aal1','role','authenticated')::text,true);
 begin perform public.csa133_read_progress(c); raise exception 'foreign session'; exception when insufficient_privilege then null; end;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',u,'session_id',us,'aal','aal1','role','authenticated')::text,true);
 update auth.sessions set not_after=now()-interval '1 second' where id=us;
 begin perform public.csa133_save_progress(l,true,null,null,null); raise exception 'expired session'; exception when insufficient_privilege then null; end;
 update auth.sessions set not_after=now()+interval '1 day' where id=us;
 perform public.csa118_revoke_access(a,ads,'aal2','progress-revoke',u,c,gid,'grant','Synthetic revoked');
 begin perform public.csa133_save_progress(l,true,null,null,null); raise exception 'revoked save'; exception when insufficient_privilege then null; end;
 begin perform public.csa133_read_progress(c); raise exception 'revoked read'; exception when insufficient_privilege then null; end;
 perform public.csa116_grant_admin(a,ads,'aal2','progress-expiry',u,c,'Timed',clock_timestamp()+interval '100 milliseconds');
 perform pg_sleep(0.15);
 begin perform public.csa133_save_progress(l,true,null,null,null); raise exception 'expired entitlement'; exception when insufficient_privilege then null; end;
 perform set_config('request.jwt.claims','{}',true);
 begin perform public.csa133_read_progress(c); raise exception 'anonymous RPC'; exception when insufficient_privilege then null; end;
 if has_table_privilege('authenticated','public.lesson_progress','INSERT') or has_table_privilege('authenticated','public.lesson_progress','SELECT') then raise exception 'direct access'; end if;
 if has_function_privilege('anon','public.csa133_save_progress(uuid,boolean,integer,numeric,integer)','EXECUTE') then raise exception 'anonymous grant'; end if;
 if (select count(*) from public.enrollment_grants where user_id=u)<>2 then raise exception 'progress changed entitlement'; end if;
end $$;
select 'ok 1 - progress persistence enforces current owner session, entitlement and typed resume';
rollback;
