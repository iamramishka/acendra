/// Countries whose name contains [query] (case-insensitive). Empty query
/// returns every country.
List<String> countrySuggestions(String query) {
  final q = query.trim().toLowerCase();
  if (q.isEmpty) return kCountries;
  return kCountries.where((c) => c.toLowerCase().contains(q)).toList();
}
